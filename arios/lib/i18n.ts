const DICT: Record<Lang, Dict> = { ja, en };

// 指定言語の辞書を返す。未定義キーは日本語にフォールバック。
export function tr(lang: Lang) {
  const d = DICT[lang] ?? ja;
  return (key: string): string => d[key] ?? ja[key] ?? key;
}
